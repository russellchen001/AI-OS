#!/usr/bin/env bash
# ============================================================
# 验收脚本模板
# 用法：复制这个文件，改名为 verify_功能名.sh，填入检查内容
# 规则：通过 exit 0，失败 exit 1
# ============================================================

FEATURE="示例功能"          # ← 改成这个脚本验收的功能名
FAILED=0

# ---- 工具函数（不用改）----------------------------------
ok()   { echo "  ✅ $1"; }
bad()  { echo "  ❌ $1"; FAILED=1; }

echo "检查：$FEATURE"

# ============================================================
# 下面是四种常见检查，用得上哪个留哪个，其余删掉
# ============================================================

# ---- 检查 1：文件是否存在 --------------------------------
if [ -f "src/auth/login.ts" ]; then
  ok "登录文件存在"
else
  bad "找不到 src/auth/login.ts"
fi

# ---- 检查 2：某条命令能否成功执行 ------------------------
if npm run build > /tmp/build.log 2>&1; then
  ok "项目能正常构建"
else
  bad "构建失败，详情看 /tmp/build.log"
fi

# ---- 检查 3：接口是否返回 200 ----------------------------
CODE=$(curl -s -o /dev/null -w "%{http_code}" --max-time 10 http://localhost:3000/api/health)
if [ "$CODE" = "200" ]; then
  ok "接口返回 200"
else
  bad "接口返回 $CODE（期望 200）"
fi

# ---- 检查 4：输出中是否包含指定内容 ----------------------
if node scripts/seed.js 2>&1 | grep -q "done"; then
  ok "数据初始化完成"
else
  bad "数据初始化未输出 done"
fi

# ============================================================
# 结论（不用改）
# ============================================================
if [ $FAILED -eq 0 ]; then
  echo "PASS: $FEATURE"
  exit 0
else
  echo "FAIL: $FEATURE"
  exit 1
fi
